import { test } from "@std/front-matter";
import { extract } from "@std/front-matter/yaml";

const ROOT = new URL("../public/docs/", import.meta.url);
const OUT = new URL("../src/lib/docs-generated.ts", import.meta.url);

type Node = {
  slug: string;
  title: string;
  order: number;
  summary?: string;
  interactive?: boolean;
  file?: string;
  children?: Node[];
};

type Fm = {
  title?: string;
  order?: number;
  summary?: string;
  interactive?: boolean;
};

async function read(rel: string): Promise<Fm> {
  const text = await Deno.readTextFile(new URL(rel, ROOT));
  return test(text, ["yaml"]) ? extract(text).attrs as Fm : {};
}

async function scanDir(rel: string): Promise<Node[]> {
  const dirUrl = new URL(rel, ROOT);
  if (!await Deno.stat(dirUrl).then(() => true, () => false)) return [];
  const files: string[] = [];
  const dirs: string[] = [];
  for await (const e of Deno.readDir(dirUrl)) {
    if (e.isDirectory) dirs.push(e.name);
    else if (e.name.endsWith(".md") && !e.name.startsWith("crate-")) {
      files.push(e.name);
    }
  }

  const nodes: Node[] = [];

  for (const name of files) {
    if (name === "index.md") continue;
    const slug = `${rel}${name.slice(0, -3)}`;
    const fm = await read(`${rel}${name}`);
    nodes.push({
      slug,
      title: fm.title ?? name.slice(0, -3),
      order: fm.order ?? 999,
      summary: fm.summary || undefined,
      interactive: fm.interactive || undefined,
      file: fm.interactive ? undefined : `${rel}${name}`,
    });
  }

  for (const name of dirs) {
    const childRel = `${rel}${name}/`;
    const slug = `${rel}${name}`;
    const fm = await read(`${childRel}index.md`).catch(() => ({} as Fm));
    const children = await scanDir(childRel);
    nodes.push({
      slug,
      title: fm.title ?? name,
      order: fm.order ?? 999,
      summary: fm.summary || undefined,
      file: `${childRel}index.md`,
      children: children.length ? children : undefined,
    });
  }

  nodes.sort((a, b) => a.order - b.order || a.title.localeCompare(b.title));
  return nodes;
}

const tree = await scanDir("");
const banner =
  "// GENERATED by scripts/gen-docs.ts from public/docs/**. Do not edit.\n" +
  "// Run `deno task gen-docs` after adding or moving a doc.\n\n" +
  'import type { DocNode } from "./docs.ts";\n\n';
await Deno.writeTextFile(
  OUT,
  `${banner}export const DOCS_TREE: DocNode[] = ${
    JSON.stringify(tree, null, 2)
  };\n`,
);
console.log(`gen-docs: wrote ${OUT.pathname}`);
